@testset "Frozen cohorts, preserved results, resumability and honest aggregation" begin
    manifest=TOML.parsefile(joinpath(catalog,"manifest.toml"))
    @test length(manifest["records"])==400
    @test manifest["audit"]["all_bits_equal"]
    @test manifest["audit"]["compared_raw_array_sets"]==450
