    mktempdir() do dir
        campaign=joinpath(dir,"campaign")
        T3.prepare(catalog,campaign;solver="highs",budget=60.,memory_gib=2.)
        config=T3.verify_campaign(campaign)
        @test config["budget_seconds"]==60.
        @test_throws ErrorException T3.prepare(catalog,campaign)
        for (seed_id,status,opt,elapsed) in ((1,"TIME_LIMIT",false,1000.),(2,"OPTIMAL",true,10.))
            id="j$(lpad(seed_id,2,'0'))_m1"; x,source=T3.frozen_record(catalog,id)
            policy=solve_sequential_dp(x).policy
            attempt=joinpath(campaign,"jobs",id*"_rdp","attempt_0001"); mkpath(attempt)
            T3.save_policy(joinpath(attempt,"policy.toml"),policy)
            data=Dict{String,Any}("id"=>id,"M"=>1,"seed_id"=>seed_id,"method"=>"rdp","solver"=>"highs",
                "label"=>"TEST FIXTURE ONLY","status"=>status,"feasible_found"=>true,"optimal_certified"=>opt,
                "instance_sha256"=>instance_hash(x),"protocol_sha256"=>T3.sha(joinpath(campaign,"protocol.toml")),
                "policy_sha256"=>T3.sha(joinpath(attempt,"policy.toml")),
                "policy_physical_exact"=>string(evaluate_policy(x,policy)),"total_runtime"=>elapsed)
            T3.atomic_toml(joinpath(attempt,"result.toml"),data)
            before=T3.sha(joinpath(attempt,"result.toml"))
            @test completed_attempt(dirname(attempt))==joinpath(attempt,"result.toml")
            @test validate_completed(joinpath(attempt,"result.toml"),config)["status"]==status
            launch_job(campaign,config,source,"rdp") # must skip without launching an optimizer
            @test T3.sha(joinpath(attempt,"result.toml"))==before
        end
        refhash=T3.sha(joinpath(campaign,"published_reference.csv"))
        report=report_campaign(campaign)
        @test T3.sha(joinpath(campaign,"published_reference.csv"))==refhash
        data,header=readdlm(joinpath(report,"aggregated.csv"),',',Any,'\n';header=true)
        col(name)=findfirst(==(name),vec(header))
        row=only(i for i in axes(data,1) if data[i,col("method")]=="rdp" && string(data[i,col("M")]) in ("1","1.0"))
        @test data[row,col("optimal")]==1
        @test data[row,col("feasible")]==2
        @test data[row,col("avg_total_runtime")]==10. # timeout excluded from the mean
        @test data[row,col("time_limit_with_policy")]==1
        @test data[row,col("not_run")]==48
        @test occursin("normalization unverified",read(joinpath(report,"root_relaxations.csv"),String))
        @test_throws ErrorException execute(campaign;methods=["irbb_fi"],sizes=[3])
    end
end
