@testset "Archived source stream, warm-up and immutable Table 3 reference" begin
    seeds=T3.Table3SourceGenerator.archived_seeds()
    @test length(seeds)==50
    @test length(unique(s.seed for s in seeds))==50
    @test all(s -> occursin("oil_seed_gurobi_",s.file),seeds)
    first=T3.Table3SourceGenerator.replay_seed(seeds[1].seed;max_m=3)
    replay=T3.Table3SourceGenerator.replay_seed(seeds[1].seed;max_m=3)
    @test [r.M for r in first]==[1,1,2,3]
    @test [T3.Table3SourceGenerator.array_hash(r.data) for r in first]==
        [T3.Table3SourceGenerator.array_hash(r.data) for r in replay]
    @test T3.Table3SourceGenerator.array_hash(first[1].data)!=T3.Table3SourceGenerator.array_hash(first[2].data)
    for (m,nv,nc) in ((1,26,19),(2,170,79),(3,1194,319),(4,8874,1279))
        @test T3.rdp_size(m)==(variables=nv,constraints=nc)
    end
    @test T3.rdp_size(8)==(variables=33729194,constraints=327679)
    published=T3.published_reference()
    @test length(published)==24
    @test only(r for r in published if r["method"]=="rdp" && r["M"]==5)["published_feasible"]==21
    # Retain the source's apparent inconsistency, not an invented correction.
    row=only(r for r in published if r["method"]=="dp_milp" && r["M"]==5)
    @test row["published_mean_total"]==400.5 && row["published_optimal"]==0
    rounded=only(r for r in published if r["method"]=="rjt" && r["M"]==4)
    @test rounded["published_constraints_text"]=="1e4"
    @test !haskey(rounded,"published_constraints")
end

@testset "Pure LP values remain separate from final MIP bounds" begin
    factory=JuMP.optimizer_with_attributes(T3.HiGHS.Optimizer,"threads"=>1)
    model=JuMP.Model(factory); JuMP.set_silent(model)
    JuMP.@variable(model,0<=v<=1,Bin)
    JuMP.@constraint(model,v<=0.5)
    JuMP.@objective(model,Max,v)
    JuMP.optimize!(model)
    @test JuMP.objective_value(model)==0.
    root=T3.root_lp(JuMP.unsafe_backend(model),factory,0.)
    @test root["root_lp_status"]=="OPTIMAL"
    @test root["root_lp_physical"]==0.5
    @test JuMP.objective_bound(model)==0.
    @test JuMP.is_binary(v)
end

@testset "Independent watchdog budgets and atomic checkpoints" begin
    config=Dict("budget_seconds"=>10.,"root_lp_budget_seconds"=>3.,
        "startup_limit_seconds"=>2.,"memory_limit_gib"=>1.)
    @test watchdog_reason("model_and_solve",9.,0,config)==""
    @test watchdog_reason("model_and_solve",11.,0,config)=="TIME_LIMIT"
    @test watchdog_reason("root_lp",4.,0,config)=="TIME_LIMIT"
    @test watchdog_reason("startup",3.,0,config)=="TIME_LIMIT"
    @test watchdog_reason("model_and_solve",0.,2^31,config)=="MEMORY_LIMIT"
    mktempdir() do dir
        file=joinpath(dir,"state.toml")
        T3.atomic_toml(file,Dict("phase"=>"model_and_solve"))
        @test TOML.parsefile(file)["phase"]=="model_and_solve"
        @test readdir(dir)==["state.toml"]
    end
end

